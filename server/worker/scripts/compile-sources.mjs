import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { parse } from 'acorn';

// Trusted, reviewed public rules are compiled at build time. Workers never eval
// imported JavaScript or construct functions from a request/source record.
const directory = dirname(fileURLToPath(import.meta.url));
const input = resolve(directory, '../../..', 'upstream/app/src/main/assets/reader-verified-sources.json');
const sources = JSON.parse(await readFile(input, 'utf8'));
const adapters = JSON.parse(await readFile(resolve(directory, '../../catalogue/source-adapters.json'), 'utf8'));
const scripts = new Set();
function visit(value) {
  if (typeof value === 'string') {
    const at = value.indexOf('@js:');
    if (at >= 0) scripts.add(value.slice(at + 4).trim());
  } else if (value && typeof value === 'object') Object.values(value).forEach(visit);
}
sources.forEach(visit);
// Adapters are checked-in public repairs, compiled just like reviewed rules.
// Uploaded source records cannot contribute executable code to this table.
adapters.adapters.forEach(adapter => visit(adapter.rules));

function compile(script) {
  const ast = parse(script, { ecmaVersion: 'latest', allowReturnOutsideFunction: false });
  const edits = [];
  function completion(node) {
    if (!node) return;
    if (node.type === 'Program' || node.type === 'BlockStatement') completion(node.body.at(-1));
    else if (node.type === 'ExpressionStatement') edits.push([node.start, node.start, 'return ('], [node.expression.end, node.end, ');']);
    else if (node.type === 'IfStatement') {
      // Wrapping a bare expression avoids returning outside the intended branch.
      for (const branch of [node.consequent, node.alternate]) {
        if (branch?.type === 'ExpressionStatement') {
          edits.push([branch.start, branch.start, '{ return ('], [branch.expression.end, branch.end, '); }']);
        } else completion(branch);
      }
    }
  }
  completion(ast);
  let output = script;
  for (const [start, end, text] of edits.sort((a,b) => b[0] - a[0])) output = output.slice(0,start) + text + output.slice(end);
  return output;
}

const knownHosts = Object.fromEntries(sources.map(source => {
  const hosts = new Set([new URL(source.bookSourceUrl).hostname]);
  for (const url of JSON.stringify(source).matchAll(/https?:\/\/([a-zA-Z0-9.-]+)/g)) hosts.add(url[1].toLowerCase());
  // Regex literals use [.] instead of dots, so reviewed cross-host aliases are explicit.
  const aliases = {
    'www.zongheng.com':['book.zongheng.com','search.zongheng.com','read.zongheng.com'],
    'www.heiyan.com':['search.heiyan.com'], 'www.ruochu.com':['search.ruochu.com'],
    'www.17k.com':['search.17k.com'], 'www.jjwxc.net':['wap.jjwxc.net'],
    'm.zhulang.com':['book.zhulang.com'], 'book.sfacg.com':['s.sfacg.com'],
    'www.ihuaben.com':['so.ihuaben.com'], 'm.kujiang.com':['www.kujiang.com'],
  };
  (aliases[new URL(source.bookSourceUrl).hostname] || []).forEach(host => hosts.add(host));
  return [source.bookSourceUrl, [...hosts].filter(host => /^[a-z0-9.-]+$/.test(host)).sort()];
}));
const publicSources = Object.fromEntries(sources.map(source => [source.bookSourceUrl, source]));
const output = `// @ts-nocheck\n// Generated by scripts/compile-sources.mjs from the 17 reviewed public rules.\n// Do not edit or add runtime eval.\nexport const reviewedHosts: Record<string,string[]> = ${JSON.stringify(knownHosts,null,2)};\nexport const reviewedSources: Record<string,Record<string,any>> = ${JSON.stringify(publicSources,null,2)};\nexport const reviewedScripts: Record<string,(environment:any)=>any> = {\n${[...scripts].sort().map(script => `${JSON.stringify(script)}: function(environment) {\nconst {java,book,baseUrl,result} = environment;\n${compile(script)}\n}`).join(',\n')}\n};\n`;
await mkdir(resolve(directory, '../src'), { recursive: true });
await writeFile(resolve(directory, '../src/compiled-sources.ts'), output);
console.log(`Compiled ${scripts.size} reviewed script bodies for ${sources.length} sources`);
await import('./compile-content-quality.mjs');
